"""Generate the N64Recomp symbol file (syms/hyp.syms.toml).

Function boundaries come from spimdisasm output for each code section,
names from n64sym (libultra signatures) and syms/manual_names.txt.

Usage: python gen_syms.py <main.s> <overlay.s> <n64sym.txt> <manual_names.txt> <out.toml>
"""
import re
import sys

# name, rom start, vram start, vram end of .text
SECTIONS = [
    ('main', 0x1000, 0x80000400, 0x80060050),
    ('game_ovl', 0xB3C70, 0x8010AAF0, 0x80123430),
]

# data embedded in .text (hand-written module's font/char tables): no functions here
DATA_RANGES = [(0x8004AB94, 0x8004C8A0)]

# named labels that are branch targets inside another function, not function starts
NOT_FUNC_STARTS = {'handle_CpU'}

# n64sym matches that are known false positives (tiny/generic bodies) in this ROM
N64SYM_REJECT = {
    '__dummy', 'n_alSynFreeFX', '__osCleanupThread', '__osGetActiveQueue', 'n_alSeqpDelete',
    'osViExtendVStart', 'osBbUsbDevGetHandle', 'alSeqFileNew', 'myfree', 'osAfterPreNMI',
    'osProfileStop', '__CallBackDmaNew', 'sqrt', 'MusFxBankNumberOfEffects', '__leoSetReset',
}


def read_funcs(asm_path):
    return [int(m.group(1), 16) for m in
            re.finditer(r'^glabel func_([0-9A-F]{8})', open(asm_path).read(), re.M)]


def read_jal_targets(asm_paths):
    targets = set()
    for path in asm_paths:
        targets |= {int(m.group(1), 16) for m in
                    re.finditer(r'jal\s+func_([0-9A-F]{8})', open(path).read())}
    return targets


def read_names(n64sym_path, manual_path):
    names = {}
    for line in open(n64sym_path):
        parts = line.split()
        if len(parts) == 2 and parts[0].startswith('8') and parts[1] not in N64SYM_REJECT:
            names.setdefault(int(parts[0], 16), parts[1])
    for line in open(manual_path):
        parts = line.split('#')[0].split()
        if len(parts) == 2:
            names[int(parts[0], 16)] = parts[1]
    return names


def main(main_s, ovl_s, n64sym_path, manual_path, out_path):
    names = read_names(n64sym_path, manual_path)
    jal_targets = read_jal_targets((main_s, ovl_s))  # catches cross-section calls
    used = set()
    out = ['# Generated by tools/gen_syms.py; do not edit by hand.\n']
    for (sec, rom, vram, vend), asm in zip(SECTIONS, (main_s, ovl_s)):
        # signature/manual names mark exact starts that spimdisasm can miss
        # (functions only reached via pointers or tail calls)
        starts = sorted(set(read_funcs(asm))
                        | {a for a in jal_targets if vram <= a < vend}
                        | {a for a, n in names.items()
                           if vram <= a < vend and n not in NOT_FUNC_STARTS})
        starts = [a for a in starts if not any(lo <= a < hi for lo, hi in DATA_RANGES)]
        assert starts[0] == vram, (sec, hex(starts[0]))
        out.append(f'[[section]]\nname = "{sec}"\nrom = 0x{rom:X}\nvram = 0x{vram:X}\n'
                   f'size = 0x{vend - vram:X}\n\nfunctions = [\n')
        for i, a in enumerate(starts):
            end = starts[i + 1] if i + 1 < len(starts) else vend
            end = min([end] + [lo for lo, _ in DATA_RANGES if a < lo < end])
            name = names.get(a, f'func_{a:08X}')
            if name in used:  # duplicate signature hit: keep the first, fall back to address name
                name = f'func_{a:08X}'
            used.add(name)
            out.append(f'    {{ name = "{name}", vram = 0x{a:08X}, size = 0x{end - a:X} }},\n')
        out.append(']\n\n')
    open(out_path, 'w', newline='\n').write(''.join(out))
    missing = sorted(n for a, n in names.items() if n not in used and 0x80000400 <= a < 0x80060050)
    print(f'{len(used)} functions; {sum(not n.startswith("func_") for n in used)} named')
    if missing:
        print('names not on a function boundary:', ' '.join(missing))


if __name__ == '__main__':
    main(*sys.argv[1:6])
