"""Generate the N64Recomp symbol file (syms/hyp.syms.toml).

Sections come from build/sections.json (tools/sections.py): main, the game overlay
and 23 scene overlays that all share vram 0x80134270. For each section the
function starts are the union of:
  - spimdisasm functions (asm/<section>.s)
  - jal targets (from every file for static sections; scene overlays only call
    into their own text, so only their own file counts for them)
  - %hi/%lo code pointers into the section's text
  - words in the section's data that point at a function boundary in its text
    (callback tables; the instruction pair before it ends in jr $ra)
  - n64sym / manual names (static sections)
Names in scene overlays are prefixed with the section name so they stay unique.

Usage: python gen_syms.py <sections.json> <rom.z64> <n64sym.txt> <manual_names.txt> <out.toml>
"""
import json
import re
import struct
import sys

# data embedded in .text (hand-written module's font/char tables): no functions here
DATA_RANGES = [(0x8004AB94, 0x8004C8A0)]

# named labels that are branch targets inside another function, not function starts
NOT_FUNC_STARTS = {'handle_CpU'}

# n64sym matches that are false positives (tiny/generic bodies) in this ROM, by address
N64SYM_REJECT = {
    0x80000500, 0x80000510, 0x80001E50, 0x800039E0, 0x80003CD4, 0x80004460, 0x80004F18,
    0x80007418, 0x800203B4, 0x80026AAC, 0x8002ACE4, 0x800353A4, 0x8003C884, 0x80048F50,
    0x8005A020, 0x80050558,
}

# Real function boundaries (jr $ra, then a new prologue) that spimdisasm folded into
# the previous function; found by Ghidra cross-check (tools/compare_funcs.py)
EXTRA_FUNC_STARTS = {
    0x8004CC5C, 0x8004CFC8, 0x8004D008, 0x8004DBD8, 0x80050558, 0x8005B6CC,
    0x8005FBF4, 0x8005FDFC, 0x8005FFFC, 0x80060028,
}

JR_RA = 0x03E00008


def read_text(path):
    return open(path, encoding='utf-8', errors='replace').read()


def read_funcs(text):
    return {int(m.group(1), 16) for m in re.finditer(r'^glabel func_([0-9A-F]{8})', text, re.M)}


def read_jal_targets(text):
    return {int(m.group(1), 16) for m in re.finditer(r'jal\s+func_([0-9A-F]{8})', text)}


def read_code_pointers(text):
    # %hi/%lo address materialization of a .text address = function pointer
    return {int(m.group(1), 16) for m in re.finditer(r'%(?:hi|lo)\(\w+?_([0-9A-F]{8})\)', text)}


def read_names(n64sym_path, manual_path):
    names = {}
    for line in open(n64sym_path):
        parts = line.split()
        if len(parts) == 2 and parts[0].startswith('8') and int(parts[0], 16) not in N64SYM_REJECT:
            names.setdefault(int(parts[0], 16), parts[1])
    for line in open(manual_path):
        parts = line.split('#')[0].split()
        if len(parts) == 2:
            names[int(parts[0], 16)] = parts[1]
    return names


def section_word(rom, sec, vram):
    o = sec['rom'] + vram - sec['vram']
    return struct.unpack('>I', rom[o:o + 4])[0]


def jump_table_targets(rom, sec, text):
    """Case labels: entries of the switch tables (jtbl_*) this section's code uses."""
    tables = sorted({int(m.group(1), 16) for m in re.finditer(r'jtbl_([0-9A-F]{8})', text)})
    targets = set()
    for i, t in enumerate(tables):
        if not sec['text_end'] <= t < sec['data_end']:
            continue
        stop = tables[i + 1] if i + 1 < len(tables) else sec['data_end']
        v = t
        while v < stop:
            p = section_word(rom, sec, v)
            if not sec['vram'] <= p < sec['text_end']:
                break
            targets.add(p)
            v += 4
    return targets


def data_pointers(rom, sec, exclude):
    """Words in the section's data pointing at a function boundary in its text."""
    out = set()
    for v in range(sec['text_end'], sec['data_end'], 4):
        p = section_word(rom, sec, v)
        if sec['vram'] <= p < sec['text_end'] and p % 4 == 0 and p not in exclude and (
                p == sec['vram'] or (p - 8 >= sec['vram'] and section_word(rom, sec, p - 8) == JR_RA)):
            out.add(p)
    return out


def main(sections_path, rom_path, n64sym_path, manual_path, out_path):
    sections = json.load(open(sections_path))
    rom = open(rom_path, 'rb').read()
    texts = {s['name']: read_text(f'asm/{s["name"]}.s') for s in sections}
    names = read_names(n64sym_path, manual_path)
    # Any section may call into main/game_ovl; overlay-internal calls stay per section.
    static_jals = set().union(*(read_jal_targets(t) for t in texts.values()))

    used = set()
    total = 0
    out = ['# Generated by tools/gen_syms.py; do not edit by hand.\n']
    for sec in sections:
        name, vram, vend = sec['name'], sec['vram'], sec['text_end']
        text = texts[name]

        def in_text(a):
            return vram <= a < vend and not any(lo <= a < hi for lo, hi in DATA_RANGES)

        starts = read_funcs(text) | read_code_pointers(text)
        starts |= data_pointers(rom, sec, jump_table_targets(rom, sec, text))
        if sec['overlapping']:
            starts |= read_jal_targets(text)
        else:
            starts |= static_jals | EXTRA_FUNC_STARTS
            starts |= {a for a, n in names.items() if n not in NOT_FUNC_STARTS}
        starts = sorted(a for a in starts if in_text(a))
        assert starts and starts[0] == vram, (name, hex(starts[0]) if starts else None)

        out.append(f'[[section]]\nname = "{name}"\nrom = 0x{sec["rom"]:X}\nvram = 0x{vram:X}\n'
                   f'size = 0x{vend - vram:X}\n\nfunctions = [\n')
        for i, a in enumerate(starts):
            end = starts[i + 1] if i + 1 < len(starts) else vend
            end = min([end] + [lo for lo, _ in DATA_RANGES if a < lo < end])
            if sec['overlapping']:
                fname = f'{name}_func_{a:08X}'
            else:
                fname = names.get(a, f'func_{a:08X}')
                if fname in used:  # duplicate signature hit: keep the first
                    fname = f'func_{a:08X}'
            used.add(fname)
            out.append(f'    {{ name = "{fname}", vram = 0x{a:08X}, size = 0x{end - a:X} }},\n')
        out.append(']\n\n')
        total += len(starts)
    open(out_path, 'w', newline='\n').write(''.join(out))
    named = sum(not (n.startswith('func_') or '_func_' in n) for n in used)
    print(f'{len(sections)} sections, {total} functions; {named} named')


if __name__ == '__main__':
    main(*sys.argv[1:6])
