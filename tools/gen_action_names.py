#!/usr/bin/env python3
"""Generate include/hyp_action_names.h from docs/action_names_en.tsv and the ROM's action table.

Usage: python tools/gen_action_names.py rom/baserom.us.z64
Each entry: action id, motion id (from the table at 0x8006B590 + 0x10), English name.
"""
import struct
import sys

rom = open(sys.argv[1], 'rb').read()
table = 0x8006B590 - 0x80000400 + 0x1000
names = {}
for line in open('docs/action_names_en.tsv', encoding='utf-8'):
    if line.startswith('#') or not line.strip():
        continue
    a, n = line.rstrip('\n').split('\t')
    names[int(a)] = n

rows = []
for a in range(330):
    motion = struct.unpack('>h', rom[table + a * 0x2C + 0x10:table + a * 0x2C + 0x12])[0]
    name = names.get(a, '').replace('\\', '\\\\').replace('"', '\\"')
    rows.append('    { %d, %d, "%s" },' % (a, motion, name))

with open('include/hyp_action_names.h', 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by tools/gen_action_names.py from docs/action_names_en.tsv. Do not edit.\n')
    f.write('#ifndef HYP_ACTION_NAMES_H\n#define HYP_ACTION_NAMES_H\n\n')
    f.write('namespace hyp::motion {\n')
    f.write('    struct ActionName { int action; int motion; const char* name; };\n')
    f.write('    inline constexpr ActionName action_names[] = {\n')
    f.write('\n'.join(rows) + '\n    };\n}\n\n#endif\n')
print('wrote %d actions' % len(rows))
